const HUBROOT = require('path').resolve(__dirname, '..').replace(/\\/g, '/'); require('./_config')();
// The work planner over HTTP: a throwaway hub whose work items come from a JSON file instead of Azure DevOps.
const { spawn } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const W = require(HUBROOT + '/lib/workdays.js');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'plapi-'));
const fake = path.join(root, 'items.json');
const mk = (id, o) => ({ id, type: 'Bug', title: 'Item ' + id, state: 'Active', assignedTo: 'Test User', priority: 2, changedDate: new Date().toISOString(), url: 'https://example/' + id, ...o });
const writeFake = (j) => fs.writeFileSync(fake, JSON.stringify(j));
let world = { me: 'Test User', assigned: [mk(1, { priority: 3 }), mk(2, { priority: 1 }), mk(3)], items: [mk(30, { assignedTo: 'Sam', title: 'Handed over' })],
  search: [mk(50, { title: 'Billing export fails', assignedTo: '', tags: 'billing' }), mk(51, { title: 'Billing screen layout', assignedTo: 'Pat', priority: 3 }), mk(52, { title: 'Billing old', state: 'Closed', assignedTo: '' })], reviews: [] };
writeFake(world);

const port = 4723; const base = 'http://localhost:' + port;
const srv = spawn(process.execPath, [HUBROOT + '/server.js'], { stdio: 'ignore', env: { ...process.env, HUB_PORT: String(port), HUB_DATA_DIR: path.join(root, 'data'), HUB_FAKE_WORKITEMS: fake, HUB_ONLY_EXTRA: '1', HUB_EXTRA_CLONES: '' } });
const H = { 'Content-Type': 'application/json', 'X-Hub-Request': '1' };
const post = (p, b, h) => fetch(base + p, { method: 'POST', headers: h || H, body: JSON.stringify(b || {}) }).then(async (r) => [r.status, await r.json().catch(() => ({}))]);
const get = (p) => fetch(base + p).then(async (r) => [r.status, await r.json()]);
let fails = 0;
const check = (n, ok, x) => { console.log((ok ? 'PASS ' : 'FAIL ') + n + (x ? '  ' + x : '')); if (!ok) fails++; };

(async () => {
  for (let i = 0; i < 60; i++) { try { await fetch(base + '/api/me'); break; } catch { await new Promise((r) => setTimeout(r, 250)); } }
  const T = W.today(); const days = W.nextWorkingDays(W.addDays(T, 1), 3);
  let [s, b] = await get('/api/planner');
  check('the board loads from the fake source: today plus 5 working days, Inbox by priority', s === 200 && b.days.length === 6 && b.days[0].date === T && b.inbox.map((t) => t.id).join() === '2,3,1', JSON.stringify([s, b.inbox && b.inbox.map((t) => t.id)]));
  check('the board says who you are and has the settings', b.me === 'Test User' && b.capacity >= 1 && b.settings.monitorEveryDays >= 1);

  console.log('--- writes are guarded');
  [s] = await post('/api/planner/schedule', { taskId: 2, date: T }, { 'Content-Type': 'application/json' });
  check('a write without the hub header is refused (403)', s === 403);
  let r = await fetch(base + '/api/planner/schedule', { method: 'POST', headers: { ...H, Origin: 'https://evil.example' }, body: '{}' });
  check('a write from another origin is refused (403)', r.status === 403);
  r = await fetch(base + '/api/planner/schedule', { method: 'POST', headers: H, body: JSON.stringify({ note: 'x'.repeat(20000) }) });
  check('an oversized body is refused (413)', r.status === 413);
  [s] = await post('/api/planner/schedule', { taskId: 'abc', date: T });
  check('a bad work item id is a 400', s === 400);

  console.log('--- schedule, move, plan lines');
  [s, r] = await post('/api/planner/schedule', { taskId: 2, date: T });
  check('schedule for today', s === 200 && r.id > 0, JSON.stringify(r));
  const [s2, r2] = await post('/api/planner/schedule', { taskId: 2, date: days[0] });
  check('the same item twice is a 409', s2 === 409 && /Already planned/.test(r2.error));
  [s] = await post('/api/planner/schedule', { taskId: 3, date: days[0] });
  [s] = await post('/api/planner/schedule', { taskId: 1, date: days[1] });
  [s, r] = await post('/api/planner/schedule', { taskId: 2, date: W.addDays(T, -1) });
  check('the past is a 400', s === 400 || s === 409);
  [s, r] = await post('/api/planner/schedule', { taskId: 999, date: T });
  check('an unknown work item is a 404', s === 404, JSON.stringify(r));
  [s, b] = await get('/api/planner');
  check('the days hold their lines and the Inbox is empty', b.days[0].items.length === 1 && b.days[0].items[0].taskId === 2 && b.inbox.length === 0 && b.days.find((d) => d.date === days[0]).items[0].taskId === 3);
  const [, plan] = await get('/api/plan?date=' + T);
  check('Today\'s plan page shows the scheduled item as a normal line, with its work item card', plan.items.length === 1 && plan.items[0].taskId === 2 && plan.items[0].text === 'Item 2' && plan.items[0].status === 'todo', JSON.stringify(plan.items.map((i) => [i.taskId, i.text])));
  const id2 = b.days[0].items[0].id;
  [s] = await post('/api/planner/move', { itemId: id2, date: days[2] });
  [, b] = await get('/api/planner');
  check('move changes the day (and Today\'s plan no longer lists it)', s === 200 && b.days[0].items.length === 0 && b.days.find((d) => d.date === days[2]).items[0].taskId === 2 && (await get('/api/plan?date=' + T))[1].items.length === 0);
  [s] = await post('/api/planner/move', { itemId: id2, date: 'later' });
  [, b] = await get('/api/planner');
  check('move to Later parks it', s === 200 && b.later.length === 1 && b.later[0].taskId === 2);
  [s] = await post('/api/planner/schedule', { taskId: 2, date: T });
  [, b] = await get('/api/planner');
  const id2b = b.days[0].items[0].id;
  [s] = await post('/api/planner/move', { itemId: id2b, date: T });
  check('moving within a day is fine', s === 200);
  [s, r] = await post('/api/planner/move', { itemId: id2b, date: '2999-01-01' });
  check('a date too far ahead is a 400', s === 400 && /60 days/.test(r.error));
  [s] = await post('/api/planner/sort', { date: days[0] });
  check('sort by priority works', s === 200);

  console.log('--- the day you work: Today\'s plan keeps working');
  const [, plan2] = await get('/api/plan?date=' + T);
  [s] = await post('/api/plan/items/' + plan2.items[0].id + '/update', { status: 'done' });
  [s, r] = await post('/api/plan/close', { date: T, carry: [], drop: [] });
  check('ticking a scheduled line and closing the day works', s === 200 && r.score && r.score.adherence === 100, JSON.stringify(r.score && r.score.adherence));

  console.log('--- revise with the latest fetch');
  world.assigned = [mk(1, { priority: 1 }), mk(3, { state: 'Resolved' }), mk(4, { priority: 2 })];
  writeFake(world);
  [s, b] = await post('/api/planner/revise');
  const kinds = b.attention.map((a) => a.kind + ':' + a.taskId).sort().join();
  check('revise flags the changed priority, the item done in Azure DevOps and the new Inbox item', /changed:1/.test(kinds) && /done-in-ado:3/.test(kinds) && b.inbox.some((t) => t.id === 4), kinds);
  check('and records that you revised today', !!b.revision || (await get('/api/planner'))[1].revision !== null);
  [s] = await post('/api/planner/ack', {});
  [, b] = await get('/api/planner');
  check('accept all clears the priority flag', !b.attention.some((a) => a.kind === 'changed'));

  console.log('--- delegation');
  [s, r] = await post('/api/planner/delegate', { taskId: 4, person: '', mode: 'monitor' });
  check('a delegation needs a person (400)', s === 400);
  [s, r] = await post('/api/planner/delegate', { taskId: 4, person: 'Sam', mode: 'monitor', note: 'Please fix', checkEveryDays: 1 });
  check('delegate to monitor (201)', s === 201 && r.id > 0);
  const did = r.id;
  [s] = await post('/api/planner/delegate', { taskId: 4, person: 'Pat', mode: 'fire_and_forget' });
  check('a second open delegation for the item is a 409', s === 409);
  [s, r] = await post('/api/planner/delegate', { taskId: 30, person: 'Pat', mode: 'fire_and_forget', wakeAfterDays: 4 });
  check('fire and forget works, including an item that is not on your assigned list', s === 201);
  [, b] = await get('/api/planner');
  check('both lanes are filled and the delegated items left the Inbox', b.delegations.monitor.length === 1 && b.delegations.fireAndForget.length === 1 && !b.inbox.some((t) => [4, 30].includes(t.id)) && b.delegations.monitor[0].nextCheck > T);
  [s, r] = await post('/api/planner/delegations/' + did + '/check', { nextInDays: 2, note: 'on track' });
  check('Checked sets the next check date', s === 200 && r.nextCheck > T);
  [s] = await post('/api/planner/delegations/' + did + '/checkin', { date: days[0] });
  [, b] = await get('/api/planner');
  check('a check-in line lands on the chosen day', s === 200 && b.days.find((d) => d.date === days[0]).items.some((i) => /Check on #4/.test(i.text)));
  [s] = await post('/api/planner/delegations/' + did + '/mode', { mode: 'fire_and_forget', wakeAfterDays: 3 });
  [, b] = await get('/api/planner');
  check('switching kind moves the card between lanes', s === 200 && b.delegations.monitor.length === 0 && b.delegations.fireAndForget.length === 2);
  [s] = await post('/api/planner/delegations/' + did + '/mode', { mode: 'monitor', checkEveryDays: 2 });
  world.assigned = world.assigned.filter((t) => t.id !== 4); world.items.push(mk(4, { state: 'Resolved', assignedTo: 'Sam' })); writeFake(world);
  [, b] = await post('/api/planner/revise');
  check('a delegated item that finished in Azure DevOps shows as ready to close', b.attention.some((a) => a.delegationId === did && a.kind === 'ready-to-close'));
  [s] = await post('/api/planner/delegations/' + did + '/close', { reason: 'Nope' });
  check('closing needs a listed reason (400)', s === 400);
  [s] = await post('/api/planner/delegations/' + did + '/close', { reason: 'Done', note: 'merged' });
  check('close works and records it', s === 200 && ((await get('/api/planner/delegations/' + did + '/history'))[1].events[0].kind === 'closed'));
  [s] = await post('/api/planner/delegations/' + did + '/check', {});
  check('a closed delegation cannot be changed (409)', s === 409);
  const [, bb] = await get('/api/planner'); const fid = bb.delegations.fireAndForget[0].id;
  [s] = await post('/api/planner/delegations/' + fid + '/take-back', { to: days[1] });
  [, b] = await get('/api/planner');
  check('take back plans the item on the chosen day', s === 200 && b.days.find((d) => d.date === days[1]).items.some((i) => i.taskId === 30) && b.delegations.fireAndForget.length === 0);
  [s, r] = await post('/api/planner/reassigned', { taskId: 3, person: 'Erin' });
  check('"no longer yours" records a monitored delegation', s === 201 && r.id > 0);

  console.log('--- topics and keyword search');
  [s] = await post('/api/planner/topics', { keyword: 'a' });
  check('a one-letter topic is a 400', s === 400);
  [s, r] = await post('/api/planner/topics', { keyword: 'Billing' });
  check('add a topic (201)', s === 201 && r.keyword === 'Billing');
  [s] = await post('/api/planner/topics', { keyword: 'billing' });
  check('the same topic again is a 409', s === 409);
  [, b] = await get('/api/planner');
  check('items matching the topic that are unassigned or owned by others are offered, finished ones are not', b.topicInbox.map((t) => t.id).join() === '50,51' && b.topicInbox[0].assignedTo === '' && b.topicInbox[1].assignedTo === 'Pat' && b.topics[0].hits === 2, JSON.stringify(b.topicInbox.map((t) => t.id)));
  [s, r] = await post('/api/planner/search', { q: 'billing' });
  check('an ad-hoc search lists the matches and saves nothing', s === 200 && r.items.length === 2 && (await get('/api/planner'))[1].topics.length === 1);
  [s] = await post('/api/planner/search', { q: '' });
  check('an empty search is a 400', s === 400);
  [s] = await post('/api/planner/schedule', { taskId: 50, date: days[2] });
  [, b] = await get('/api/planner');
  check('planning a topic item takes it out of the topic list', s === 200 && !b.topicInbox.some((t) => t.id === 50));
  [s] = await post('/api/planner/topics/' + b.topics[0].id + '/remove');
  check('a topic can be removed', s === 200 && (await get('/api/planner'))[1].topics.length === 0);

  console.log('--- data stays safe');
  const health = (await get('/api/health'))[1].db;
  check('schema is current and the new tables are counted', health.schemaVersion === health.expectedSchemaVersion && health.counts.delegations >= 3, JSON.stringify(health.counts));
  srv.kill();
  console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
  setTimeout(() => { try { fs.rmSync(root, { recursive: true, force: true }); } catch { /* temp */ } process.exit(fails ? 1 : 0); }, 600);
})().catch((e) => { console.error(e); srv.kill(); process.exit(1); });
